#!/usr/bin/env perl
# gen-dng-usage.pl SPEC_TEXT > src/dng_usage.zig
#
# Derives each DNG tag's "Usage" IFD class from the tag definition blocks of
# the Digital Negative Specification 1.6.0.0, as plain text (pdftotext
# -layout of Adobe's PDF; the text is not committed). A block has a
# "Tag  N (X.H)" line and, below it, a "Usage  <class>" line. Fails unless
# every Usage value maps to a known class, so a new class is not dropped.
use strict;
use warnings;

my %class = (
    'IFD 0'                        => 'ifd0',
    'IFD 0 or Camera Profile IFD'  => 'ifd0_or_camera_profile',
    'Raw IFD'                      => 'raw',
    'Preview IFD'                  => 'preview',
    'Semantic Mask IFD'            => 'semantic_mask',
    'Raw IFD or Enhanced IFD'      => 'raw_or_enhanced',
    'IFD 0 or Enhanced IFD'        => 'ifd0_or_enhanced',
    'Enhanced IFD'                 => 'enhanced',
    'IFD'                          => 'any',
);
my $path = shift or die "usage: gen-dng-usage.pl SPEC_TEXT\n";
open my $f, '<', $path or die "$path: $!\n";
my ($tag, %usage);
while (<$f>) {
    $tag = $1 if /^Tag\s+(\d+)\s+\(/;
    if (/^Usage\s+(.*?)\s*$/ && defined $tag) {
        my $c = $class{$1} // die "unknown Usage '$1' for tag $tag\n";
        die "tag $tag has two Usage lines\n" if exists $usage{$tag} && $usage{$tag} ne $c;
        $usage{$tag} = $c;
        undef $tag;
    }
}
die "no tags found\n" unless %usage;
print <<'HEAD';
//! Where each DNG tag belongs: the "Usage" line of its definition block in
//! the Digital Negative Specification 1.6.0.0. Generated by
//! tools/gen-dng-usage.pl from the specification's text; do not edit.
//! A tag outside its Usage IFD is should_deviation rule 14 (validate D7,
//! 2026-11-07). A parity test ties this table to the DNG rows in
//! ifd_conformance, both ways.

pub const Usage = enum { ifd0, ifd0_or_camera_profile, raw, preview, semantic_mask, raw_or_enhanced, ifd0_or_enhanced, enhanced, any };

pub const Entry = struct { tag: u16, usage: Usage };

pub const table = [_]Entry{
HEAD
printf "    .{ .tag = %d, .usage = .%s },\n", $_, $usage{$_} for sort { $a <=> $b } keys %usage;
print "};\n\n";
print <<'TAIL';
/// The Usage class of DNG tag `tag`, or null for a tag DNG does not define.
pub fn of(tag: u16) ?Usage {
    for (table) |e| if (e.tag == tag) return e.usage;
    return null;
}
TAIL
